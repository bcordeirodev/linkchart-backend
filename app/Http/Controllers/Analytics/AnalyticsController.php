<?php

namespace App\Http\Controllers\Analytics;

use App\Contracts\Analytics\LinkAnalyticsOrchestratorInterface;
use App\Contracts\Analytics\TemporalAnalyticsInterface;
use App\DTOs\Analytics\AnalyticsFilters;
use App\Http\Controllers\BaseController;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

/**
 * Analytics controller for per-link advanced analytics endpoints.
 *
 * Extends BaseController to inherit findOwnedLink, linkNotFound, and serverError.
 * Depends on LinkAnalyticsOrchestratorInterface (injected, resolved from the
 * concrete LinkAnalyticsOrchestrator since R-13) and TemporalAnalyticsInterface
 * for the merged temporal endpoint.
 *
 * Routes (all under api.auth:api + verified middleware, prefix /api/analytics/link/{linkId}):
 *   GET /api/analytics/link/{linkId}/dashboard     → getLinkDashboardData
 *   GET /api/analytics/link/{linkId}/comprehensive → getLinkAnalytics
 *   GET /api/analytics/link/{linkId}/geographic    → getGeographicAnalytics
 *   GET /api/analytics/link/{linkId}/insights      → getBusinessInsights
 *   GET /api/analytics/link/{linkId}/temporal      → getTemporalAnalytics
 *   GET /api/analytics/link/{linkId}/audience      → getAudienceAnalytics
 *
 * Cross-mount note: GET /api/links/{id}/analytics is physically defined in the
 * links route group (routes/api.php line 96) but is handled by this controller's
 * getLinkSummaryAnalytics action, not by LinkController.
 *
 * Heatmap data was folded into getGeographicAnalytics in commit 00e6a3f; there
 * is no longer a dedicated /heatmap endpoint.
 */
class AnalyticsController extends BaseController
{
    public function __construct(
        private LinkAnalyticsOrchestratorInterface $analyticsService,
        private TemporalAnalyticsInterface $temporalService
    ) {}

    /**
     * GET /api/analytics/link/{linkId}/comprehensive
     *
     * Return comprehensive analytics for a single link by delegating to
     * LinkAnalyticsOrchestratorInterface::getComprehensiveLinkAnalytics.
     *
     * Middleware: api.auth:api, verified
     * Auth: required
     * Owner check: yes — uses findOwnedLink.
     *
     * Response shape: { success: true, data: ComprehensiveAnalytics }
     */
    public function getLinkAnalytics(int $linkId): JsonResponse
    {
        try {
            $link = $this->findOwnedLink($linkId);
            if (! $link) {
                return $this->linkNotFound();
            }

            $analytics = $this->analyticsService->getComprehensiveLinkAnalytics($linkId);

            return response()->json([
                'success' => true,
                'data' => $analytics,
            ]);
        } catch (\Exception $e) {
            return $this->serverError('Erro ao buscar analytics do link.', $e);
        }
    }

    /**
     * GET /api/analytics/link/{linkId}/geographic
     *
     * Return detailed geographic analytics (country, city, continent breakdowns)
     * with heatmap data folded in (heatmap was merged here in commit 00e6a3f).
     * Delegates to LinkAnalyticsOrchestratorInterface::getLinkGeographicAnalytics,
     * which returns a { data, meta } payload that is forwarded directly.
     *
     * Middleware: api.auth:api, verified
     * Auth: required
     * Owner check: yes — uses findOwnedLink.
     *
     * Response shape: { success: true, data: GeographicData, meta: GeographicMeta }
