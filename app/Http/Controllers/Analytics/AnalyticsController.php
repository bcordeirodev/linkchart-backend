            if (! $link) {
                return $this->linkNotFound();
            }

            $payload = $this->analyticsService->getLinkGeographicAnalytics($linkId);

            return response()->json([
                'success' => true,
                'data' => $payload['data'],
                'meta' => $payload['meta'],
            ]);
        } catch (\Exception $e) {
            return $this->serverError('Erro ao buscar analytics geográficos.', $e);
        }
    }

